  const storageKey = 'khuririm-language';
  let language = 'pt';
  const t = key => translations[language][key] ?? translations.pt[key] ?? key;

  function setLanguage(nextLanguage) {
    language = Object.hasOwn(translations, nextLanguage) ? nextLanguage : 'pt';
    document.documentElement.lang = language === 'en' ? 'en' : 'pt-BR';
    // Use textContent: a tradução não injeta HTML e preserva a estrutura da página.
    document.querySelectorAll('[data-i18n]').forEach(element => {
      element.textContent = t(element.dataset.i18n);
    });
    ['alt', 'aria-label', 'content'].forEach(attribute => {
      document.querySelectorAll(`[data-i18n-${attribute}]`).forEach(element => {
        element.setAttribute(attribute, t(element.getAttribute(`data-i18n-${attribute}`)));
      });
    });
    document.querySelectorAll('[data-language]').forEach(button => {
      button.setAttribute('aria-pressed', String(button.dataset.language === language));
    });
    const menu = document.querySelector('.menu-toggle');
    if (menu) menu.setAttribute('aria-label', t(menu.getAttribute('aria-expanded') === 'true' ? 'menu.close' : 'menu.open'));
    // Alguns navegadores bloqueiam armazenamento; a alternância continua funcionando.
    try { localStorage.setItem(storageKey, language); } catch (_) { /* preferência apenas nesta página */ }
    document.dispatchEvent(new CustomEvent('languagechange', { detail: { language } }));
  }

  window.SiteI18n = { t, setLanguage };
  let savedLanguage = 'pt';
  try { savedLanguage = localStorage.getItem(storageKey) || 'pt'; } catch (_) { /* usar português */ }
  setLanguage(savedLanguage);
  document.querySelectorAll('[data-language]').forEach(button => {
    button.addEventListener('click', () => setLanguage(button.dataset.language));
  });

